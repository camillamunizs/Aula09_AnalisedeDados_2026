def dobro(x):
    res = x * 2
    return res


def triplo(x):
    res = x * 3
    return res


def quadrado(x):
    res = x * x
    return res


numero = float(input('\nInforme o número: '))
resultado = dobro(numero)
print(f'O Dobro é: {resultado}')


resultado = triplo(numero)
print(f'O Triplo é: {resultado}')


resultado = quadrado(numero)
print(f'O Quadrado é: {resultado}')











